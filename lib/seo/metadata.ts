import type { Metadata } from "next";
import { site } from "@/data/site";
import type { PageSeo } from "@/data/seo";

interface PageMetadataInput extends PageSeo {
  /** Path starting with "/" — the page's own URL. */
  path: string;
  /** Canonical path when it differs from `path` (consolidates duplicate content). */
  canonicalPath?: string;
  /** Use `title` as-is, without the " | IMTA AI Institute" suffix. */
  absoluteTitle?: boolean;
  /** Keep the page out of search results (still crawlable for links). */
  noIndex?: boolean;
  /** Set false when the route has its own opengraph-image file. */
  defaultImage?: boolean;
}

/** Shared social image generated by app/opengraph-image.tsx. */
const DEFAULT_OG_IMAGE = { url: "/opengraph-image", width: 1200, height: 630, alt: `${site.name} — live online AI courses` };

/**
 * Consistent per-page metadata: unique title + description, canonical URL,
 * Open Graph and Twitter cards (US English locale).
 */
export function createPageMetadata({
  title,
  description,
  path,
  canonicalPath,
  absoluteTitle = false,
  noIndex = false,
  defaultImage = true,
}: PageMetadataInput): Metadata {
  const fullTitle = absoluteTitle ? title : `${title} | ${site.name}`;
  const images = defaultImage ? [DEFAULT_OG_IMAGE] : undefined;

  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: canonicalPath ?? path },
    robots: noIndex ? { index: false, follow: true } : undefined,
    openGraph: {
      title: fullTitle,
      description,
      url: path,
      siteName: site.name,
      type: "website",
      locale: "en_US",
      ...(images ? { images } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      ...(images ? { images: images.map((i) => i.url) } : {}),
    },
  };
}
